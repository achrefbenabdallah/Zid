/**
 * Shape every locale must provide. Extra keys are allowed so languages with more
 * plural forms (Arabic: _zero/_two/_few/_many) can add them.
 */
type Loose<T> = { [K in keyof T]: T[K] extends string ? string : Loose<T[K]> } & Record<string, unknown>;
export type Translation = Loose<typeof en>;
